function fig_style()
% FIG_STYLE  One consistent look for every report figure (font, sizes, white
%            background). Call once at the top of a script that draws figures.
set(groot, ...
    'DefaultFigureColor',        'w', ...
    'DefaultAxesFontName',       'Arial', ...
    'DefaultTextFontName',       'Arial', ...
    'DefaultAxesFontSize',       11, ...
    'DefaultTextFontSize',       11, ...
    'DefaultLegendFontSize',     10, ...
    'DefaultColorbarFontSize',   10, ...
    'DefaultAxesLineWidth',      0.8, ...
    'DefaultAxesBox',            'on', ...
    'DefaultAxesTickDir',        'in', ...
    'DefaultAxesXGrid',          'on', ...
    'DefaultAxesYGrid',          'on', ...
    'DefaultAxesGridAlpha',      0.25);
end
